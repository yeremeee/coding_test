WITH MAX_PRICE_TABLE AS (
    SELECT CATEGORY,
           MAX(PRICE) AS MAX_PRICE
    FROM FOOD_PRODUCT
    WHERE CATEGORY IN ('과자', '국', '김치', '식용유')
    GROUP BY CATEGORY
)

SELECT P.CATEGORY,
       M.MAX_PRICE,
       P.PRODUCT_NAME
FROM FOOD_PRODUCT P
JOIN MAX_PRICE_TABLE M
    ON P.CATEGORY = M.CATEGORY
    AND P.PRICE = M.MAX_PRICE
ORDER BY M.MAX_PRICE DESC;