WITH OA AS (
    SELECT PRODUCT_ID,
           SUM(AMOUNT) AS TOTAL_AMOUNT
    FROM FOOD_ORDER
    WHERE YEAR(PRODUCE_DATE) = 2022
      AND MONTH(PRODUCE_DATE) = 5
    GROUP BY PRODUCT_ID
)

SELECT P.PRODUCT_ID,
       P.PRODUCT_NAME,
       P.PRICE * OA.TOTAL_AMOUNT AS TOTAL_SALES
FROM FOOD_PRODUCT P
JOIN OA
    ON P.PRODUCT_ID = OA.PRODUCT_ID
ORDER BY TOTAL_SALES DESC, P.PRODUCT_ID ASC;

